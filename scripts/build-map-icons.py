"""Regenerate the map's Phosphor subset with FontTools (pip install fonttools brotli)."""
from pathlib import Path
import re
from fontTools import subset
from fontTools.ttLib import TTFont

root = Path(__file__).resolve().parent.parent
sources = [root / 'server.js', *[p for p in (root / 'public').iterdir() if p.suffix in ('.html', '.js')]]
text = '\n'.join(p.read_text(encoding='utf-8') for p in sources)
names = set(re.findall(r'ph-([a-z][a-z0-9-]*)', text))
names.update(re.findall(r'icon:\s*["\']([a-z-]+)', text))
names.update(['sun', 'moon'])
package = root / 'node_modules/@phosphor-icons/web/src/regular'
css = (package / 'style.css').read_text(encoding='utf-8')
rules = re.findall(r'\.ph\.ph-([a-z0-9-]+):before\s*\{\s*content:\s*"\\([a-f0-9]+)";\s*\}', css)
used = [(name, code) for name, code in rules if name in names]
options = subset.Options()
options.flavor = 'woff2'
font = TTFont(package / 'Phosphor.woff2')
subsetter = subset.Subsetter(options=options)
subsetter.populate(unicodes=[int(code, 16) for _, code in used])
subsetter.subset(font)
font.save(root / 'public/map-icons.woff2')
base = css[css.index('.ph {'):css.index('.ph.ph-')]
face = '@font-face{font-family:Phosphor;src:url("/map-icons.woff2?v=20261117-1") format("woff2");font-weight:normal;font-style:normal;font-display:swap;}\n'
rules = '\n'.join(f'.ph.ph-{name}:before{{content:"\\{code}";}}' for name, code in used)
(root / 'public/map-icons.css').write_text('/* Phosphor Icons 2.1.1, MIT license; generated by scripts/build-map-icons.py. */\n' + face + base + rules + '\n', encoding='utf-8')
print(f'Generated {len(used)} icons: {(root / "public/map-icons.woff2").stat().st_size} bytes')
